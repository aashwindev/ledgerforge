// Retrieval benchmark on real Flask history.
// Each case is a real feature or bug-fix commit: the request is the commit subject,
// the workspace is the parent commit, and the answer is the files the commit changed.
// We measure how many of those files the Context Pack puts in front of the model
// before turn 1, against plain ranked search with the same number of slots.
//
// Usage: npx esbuild scripts/bench-retrieval.ts --bundle --platform=node --outfile=dist/bench.js
//        node dist/bench.js <flask clone> [--out docs/retrieval-benchmark.md]
import { execFileSync } from 'child_process';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { Workspace } from '../src/workspace';
import { buildContextPack } from '../src/context';
import { searchCode } from '../src/tools';

const [flask, , out] = process.argv.slice(2);
if (!flask) { console.error('usage: node dist/bench.js <flask clone> [--out file.md]'); process.exit(1); }
const git = (...a: string[]) => execFileSync('git', ['-C', flask, ...a], { encoding: 'utf8' }).trim();

const HEAD = '22d92470'; // Flask 3.1.3, the commit the demo uses
const MAINTENANCE = /dev dependencies|mypy|pyright|ruff|type (hint|check|annotation)|typing|annotat|refactor|release|version|deprecat|drop support|use uv|project files|pre-commit|lint|format|noqa|merge|revert|docstring|typo|rename|move|cleanup|clean up|test|ci\b/i;
const RELEVANT = (f: string) => /^(src\/flask\/.*\.py|tests\/.*\.py|docs\/.*\.rst|CHANGES\.rst)$/.test(f);

const commits = git('log', '--no-merges', '--since=2021-01-01', '--format=%h|%s', HEAD, '--', 'src/flask/*.py')
  .split('\n').map(l => { const i = l.indexOf('|'); return { sha: l.slice(0, i), subject: l.slice(i + 1).replace(/\s*\(#\d+\)$/, '') }; })
  .filter(c => !MAINTENANCE.test(c.subject) && c.subject.split(/\s+/).length >= 3);

interface Row { sha: string; subject: string; truth: string[]; pack: string[]; search: string[] }
const rows: Row[] = [];

(async () => {
  for (const c of commits) {
    const truth = git('show', '--name-only', '--format=', c.sha).split('\n').filter(RELEVANT);
    if (!truth.some(f => f.startsWith('src/'))) continue;
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'lf-bench-'));
    git('worktree', 'add', '--detach', '-q', dir, `${c.sha}^`);
    try {
      const ws = new Workspace(dir);
      const pack = await buildContextPack(ws, c.subject);
      const included = pack.rows.filter(r => r.included).map(r => r.path);
      const k = included.length;
      const search = (await searchCode(ws, c.subject, k)).split('\n').filter(l => /^\S/.test(l)).map(l => l.split(/\s+/)[0]);
      rows.push({ sha: c.sha, subject: c.subject, truth, pack: included, search });
      process.stderr.write('.');
    } finally {
      git('worktree', 'remove', '--force', dir);
    }
  }
  process.stderr.write('\n');

  const pct = (n: number, d: number) => (d ? `${Math.round((100 * n) / d)}%` : 'n/a');
  const kinds: [string, (f: string) => boolean][] = [
    ['implementation (src/flask)', f => f.startsWith('src/')],
    ['tests', f => f.startsWith('tests/')],
    ['docs pages', f => f.startsWith('docs/')],
    ['changelog', f => f === 'CHANGES.rst'],
    ['all changed files', () => true],
  ];
  const table = kinds.map(([label, is]) => {
    const t = rows.flatMap(r => r.truth.filter(is).map(f => ({ f, r })));
    const inPack = t.filter(({ f, r }) => r.pack.includes(f)).length;
    const inSearch = t.filter(({ f, r }) => r.search.includes(f)).length;
    return `| ${label} | ${t.length} | ${pct(inPack, t.length)} | ${pct(inSearch, t.length)} |`;
  });
  const implHit = rows.filter(r => r.truth.some(f => f.startsWith('src/') && r.pack.includes(f))).length;
  const implHitSearch = rows.filter(r => r.truth.some(f => f.startsWith('src/') && r.search.includes(f))).length;
  const avgSlots = rows.reduce((s, r) => s + r.pack.length, 0) / rows.length;

  const md = [
    '# Retrieval benchmark',
    '',
    `Generated by \`scripts/bench-retrieval.ts\` on pallets/flask history up to ${HEAD} (Flask 3.1.3).`,
    '',
    `**Cases:** ${rows.length} real feature and bug-fix commits since 2021 that change \`src/flask\`. Maintenance commits (dependency bumps, typing, lint, refactors, releases) are filtered out by subject.`,
    '**Request:** the commit subject, as written by the Flask maintainers. It is often terse, which makes this harder than a typed instruction.',
    '**Workspace:** the parent commit, so the answer is not in the files yet.',
    '**Answer:** the files the commit changed under `src/flask`, `tests`, `docs` and `CHANGES.rst`.',
    `**Compared:** the Context Pack (8k-token budget, ${avgSlots.toFixed(1)} files on average) against plain ranked search given the same number of files per case.`,
    '',
    '| Changed files of this kind | Count | In Context Pack | In plain search, same slots |',
    '|---|---|---|---|',
    ...table,
    '',
    `**At least one changed implementation file in the pack:** ${implHit}/${rows.length} cases (${pct(implHit, rows.length)}); plain search ${implHitSearch}/${rows.length} (${pct(implHitSearch, rows.length)}).`,
    '',
    '## Per case',
    '',
    '| Commit | Request | Changed | In pack |',
    '|---|---|---|---|',
    ...rows.map(r => `| ${r.sha} | ${r.subject.replace(/\|/g, '\\|')} | ${r.truth.length} | ${r.truth.filter(f => r.pack.includes(f)).length} |`),
    '',
  ].join('\n');
  if (out) fs.writeFileSync(out, md); else console.log(md);
})();
